create table orders (
  id int8 generated always as identity primary key,
  number int4 generated by default as identity,
  status order_status not null default 'new',
  shipping order_status check (shipping in ('paid', 'shipped')),
  review order_status check (review in ('new', 'paid', 'shipped')),
  kind kind not null,
  channel text not null check (channel in ('web', 'shop', 'it''s', 'say "hi"')),
  priority int2 not null default 1 check (priority in (1, 2, -3)),
  region varchar(8) check (region = 'eu'),
  rank int4 not null default 10 check (rank in (10, 20)),
  outer_kind outer_kind,
  inner_kind inner_kind,
  pieces defaulted,
  tone text collate ci not null default 'soft' check (tone in ('loud', 'soft')),
  ci_kind ci_kind,
  quantity positive not null,
  tags tag_list not null default '{}',
  labels text[] not null default '{}' check (array_position(labels, null) is null),
  notes text[],
  scores int4[] not null default '{}',
  coupons uuid[],
  history order_status[],
  kinds kind[],
  moments moment[],
  amount numeric(12, 2) not null,
  total numeric(12, 2) generated always as (amount * 2) stored,
  note note,
  email citext unique,
  payload jsonb not null default '{}',
  placed_on date not null default current_date,
  placed_at timestamptz not null default now(),
  receipt bytea,
  serial_no serial,
  attributes hstore,
  required_attributes hstore not null,
  attribute_sets hstore[],
  constraint orders_total_positive check (total >= 0)
);

comment on table orders is 'What customers buy.';

comment on column orders.status is 'Where the order is.
It only moves forward.';

comment on column orders.kind is 'A comment that holds */ in it.';

create unique index orders_number_key on orders (number);

create unique index orders_open_email_key on orders (email) where status = 'new';

create table order_items (
  order_id int8 not null references orders (id),
  line int2 not null,
  "Mixed Case" text,
  "select" text,
  "2fa" bool,
  primary key (order_id, line)
);

create table bookings (
  id int4 primary key,
  during tstzrange not null,
  exclude using gist (during with &&)
);

create table events (
  id int8 not null,
  at timestamptz not null,
  primary key (id, at)
) partition by range (at);

create table events_2026 partition of events
  for values from ('2026-01-01') to ('2027-01-01');

create view open_orders as
  select id, status, note, placed_at from orders where status <> 'shipped';

create materialized view order_counts as
  select status, count(*) as orders from orders group by status;

create table billing.invoices (
  id int8 generated always as identity primary key,
  state billing.invoice_state not null default 'draft',
  order_id int8 references orders (id) on delete restrict
);

create table empty ();

create extension if not exists file_fdw;

create server files foreign data wrapper file_fdw;

create foreign table imported (
  code text not null,
  kind text check (kind in ('a', 'b')),
  level kind,
  status order_status
) server files options (filename '/dev/null', format 'csv');
