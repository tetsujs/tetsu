/**
 * Writing the file of queries: each shape its declarations take, short and
 * too long for a line, and the whole file held to Biome with the
 * repository's settings — Prettier's defaults — which must leave it as it
 * is and find nothing to lint.
 *
 * @module
 */

import { afterAll, describe, expect, test } from "bun:test";
import { mkdtemp, rm } from "node:fs/promises";
import { join } from "node:path";
import type { TsType, Values } from "./catalog.ts";
import type { DescribedField, DescribedQuery } from "./describe.ts";
import { parseQuery } from "./query-files.ts";
import { renderQueries } from "./render-queries.ts";

const root = join(import.meta.dir, "../../..");
const biome = join(root, "node_modules/.bin/biome");

/**
 * A directory in the package, so that the repository's settings hold for
 * it, which git ignores in case a run ends before it is removed.
 */
const scratch = await mkdtemp(join(import.meta.dir, "../test-utils/render-"));

afterAll(async () => {
  await rm(scratch, { recursive: true, force: true });
});

/** What `biome check` says of a source, kept in a file of the package. */
async function check(source: string) {
  const path = join(scratch, `${Bun.randomUUIDv7()}.ts`);

  await Bun.write(path, source);

  const result = Bun.spawnSync(
    [biome, "check", "--vcs-use-ignore-file=false", path],
    { cwd: root, stdout: "pipe", stderr: "pipe" },
  );

  return {
    exitCode: result.exitCode,
    output: `${result.stdout.toString()}${result.stderr.toString()}`,
  };
}

const keyword = (name: string): TsType => ({ kind: "keyword", name });
const same = (type: TsType): Values => ({ reads: type, writes: type });
const BIGINT = same(keyword("bigint"));
const STRING = same(keyword("string"));

/** A query of a file in `queries`, described as `shape` says. */
function query(
  name: string,
  source: string,
  shape: {
    readonly fields?: readonly DescribedField[] | null;
    readonly literal?: Readonly<Record<string, string>>;
    readonly values?: Values;
  } = {},
): DescribedQuery {
  const file = parseQuery(
    `/app/queries/${name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}.sql`,
    name,
    source,
  );

  return {
    file,
    parameters: file.parameters.map((parameter) => ({
      ...parameter,
      values: shape.values ?? BIGINT,
      literal: shape.literal?.[parameter.name],
    })),
    fields:
      shape.fields === undefined
        ? [{ name: "id", values: BIGINT, nullable: false }]
        : shape.fields,
  };
}

/** The file of `queries`, written in `/app/src`, its types in `/app/src/db.generated.ts`. */
function file(...queries: DescribedQuery[]): string {
  return renderQueries(queries, {
    base: "/app/src",
    types: "/app/src/db.generated.ts",
  });
}

/** The part of a file after its imports. */
function body(source: string): string {
  return source.slice(
    source.indexOf("\n\n", source.indexOf("import type * as")) + 2,
  );
}

describe("the file of queries", () => {
  test("imports what it uses, and the file of types as a namespace", async () => {
    const source = file(query("byId", "select id from t where id = :id"));

    expect(source).toStartWith(`/**
 * The functions of the query files, typed by the database the migrations
 * build, as Postgres describes each query.
 *
 * Generated by \`tetsu-sql types:generate\`: change the queries, not this
 * file, and generate it again.
 *
 * @module
 */

import { queryRows } from "@tetsujs/sql";
import type { Kysely } from "kysely";
import type * as Database from "./db.generated.ts";
`);
    expect(file(query("drop", "delete from t", { fields: null }))).toContain(
      'import { queryCount } from "@tetsujs/sql";',
    );
    expect(
      renderQueries([query("a", "select 1 as id")], {
        base: "/app/src/queries",
        types: "/app/types/db.ts",
      }),
    ).toContain('import type * as Database from "../../types/db.ts";');
  });

  test("of no queries is a module of nothing", async () => {
    const source = file();

    expect(source).toEndWith(" */\n\nexport {};\n");
    expect(await check(source)).toEqual({
      exitCode: 0,
      output: expect.any(String),
    });
  });

  test("writes a query's rows, its parameters, its text and its function", async () => {
    expect(
      body(
        file(
          query(
            "byId",
            "-- An order.\nselect id, note from t where id = :id and note = :note?",
            {
              fields: [
                { name: "id", values: BIGINT, nullable: false },
                { name: "note", values: STRING, nullable: true },
              ],
            },
          ),
        ),
      ),
    ).toBe(`/** A row of {@link byId}. */
export interface ByIdRow {
  id: bigint;
  note: string | null;
}

/** The parameters of {@link byId}. */
export interface ByIdParams {
  id: bigint;
  note: bigint | null;
}

const BY_ID = {
  text: \`-- An order.
select id, note from t where id = $1 and note = $2\`,
  names: ["id", "note"],
  arrays: {},
};

/**
 * An order.
 *
 * \`../queries/by-id.sql\`
 */
export function byId(
  db: Kysely<Database.DB>,
  params: ByIdParams,
): Promise<ByIdRow[]> {
  return queryRows(db, BY_ID, params);
}
`);
  });

  test("writes a function of no parameters, and one that counts", async () => {
    expect(body(file(query("a", "select 1 as id")))).toContain(
      "export function a(db: Kysely<Database.DB>): Promise<ARow[]> {\n  return queryRows(db, A);\n}",
    );
    expect(
      body(file(query("ab", "delete from t where id = :id", { fields: null }))),
    ).toBe(`/** The parameters of {@link ab}. */
export interface AbParams {
  id: bigint;
}

const AB = {
  text: \`delete from t where id = $1\`,
  names: ["id"],
  arrays: {},
};

/** \`../queries/ab.sql\` */
export function ab(db: Kysely<Database.DB>, params: AbParams): Promise<bigint> {
  return queryCount(db, AB, params);
}
`);
  });

  test("writes the types of the file of types by its namespace, arrays of unions in brackets", async () => {
    const status: TsType = { kind: "alias", name: "OrderStatus" };
    const source = file(
      query("statuses", "select s from t where s = any(:s)", {
        fields: [
          {
            name: "s",
            values: same({
              kind: "array",
              element: { kind: "union", members: [status, keyword("null")] },
              readonly: false,
            }),
            nullable: true,
          },
        ],
        values: same({ kind: "array", element: status, readonly: true }),
        literal: { s: "," },
      }),
    );

    expect(source).toContain("  s: (Database.OrderStatus | null)[] | null;");
    expect(source).toContain("  s: readonly Database.OrderStatus[];");
    expect(source).toContain('  arrays: { s: "," },');
  });

  test("leaves NULL out of unknown, which holds it", async () => {
    expect(
      file(
        query("a", "select x from t", {
          fields: [
            { name: "x", values: same(keyword("unknown")), nullable: true },
          ],
        }),
      ),
    ).toContain("  x: unknown;");
  });

  test("quotes a key that is not a name, and escapes the text as a template", async () => {
    const source = file(
      query(
        "odd",
        // biome-ignore lint/suspicious/noTemplateCurlyInString: the text of the query holds what a template would read as a placeholder
        'select 1 as "Mixed Case", 2 as "2fa", \'`${x}\\\'\' as y',
        {
          fields: [
            { name: "Mixed Case", values: BIGINT, nullable: false },
            { name: "2fa", values: BIGINT, nullable: false },
            { name: "__proto__", values: BIGINT, nullable: false },
          ],
        },
      ),
    );

    expect(source).toContain(
      '  "Mixed Case": bigint;\n  "2fa": bigint;\n  __proto__: bigint;',
    );
    expect(source).toContain(
      // biome-ignore lint/suspicious/noTemplateCurlyInString: the template the file writes holds the placeholder escaped
      '  text: `select 1 as "Mixed Case", 2 as "2fa", \'\\`\\${x}\\\\\'\' as y`,',
    );
    expect((await check(source)).exitCode).toBe(0);
  });
});

describe("a query's text", () => {
  test("keeps a carriage return as an escape, which a template would read as a line break", async () => {
    const source = file(query("crlf", "select 'a\r\nb' as id\r\nfrom t"));

    expect(source).toContain("  text: `select 'a\\r\nb' as id\\r\nfrom t`,");
    expect(await check(source)).toEqual({
      exitCode: 0,
      output: expect.any(String),
    });
  });
});

describe("a declaration too long for its line", () => {
  test("breaks a function's parameters, its call's arguments, and its constant after its name", async () => {
    const name = "theOrdersOfACustomerThatArePaidAndShippedAndNotYetReceived";
    const source = file(query(name, "select 1 as id where 1 = :id"));

    expect(
      source,
    ).toContain(`const THE_ORDERS_OF_A_CUSTOMER_THAT_ARE_PAID_AND_SHIPPED_AND_NOT_YET_RECEIVED =
  {
    text: \`select 1 as id where 1 = $1\`,
    names: ["id"],
    arrays: {},
  };`);
    expect(source).toContain(`export function ${name}(
  db: Kysely<Database.DB>,
  params: TheOrdersOfACustomerThatArePaidAndShippedAndNotYetReceivedParams,
): Promise<TheOrdersOfACustomerThatArePaidAndShippedAndNotYetReceivedRow[]> {
  return queryRows(
    db,
    THE_ORDERS_OF_A_CUSTOMER_THAT_ARE_PAID_AND_SHIPPED_AND_NOT_YET_RECEIVED,
    params,
  );
}`);
    expect(await check(source)).toEqual({
      exitCode: 0,
      output: expect.any(String),
    });
  });

  test("breaks the names and the arrays of its parameters a line each", async () => {
    const names = Array.from({ length: 9 }, (_, index) => `parameter${index}`);
    const source = file(
      query("many", `select ${names.map((name) => `:${name}`).join(", ")}`, {
        fields: null,
        literal: Object.fromEntries(names.map((name) => [name, ","])),
      }),
    );

    expect(source).toContain(
      `  names: [\n${names.map((name) => `    "${name}",`).join("\n")}\n  ],`,
    );
    expect(source).toContain(
      `  arrays: {\n${names.map((name) => `    ${name}: ",",`).join("\n")}\n  },`,
    );
    expect(await check(source)).toEqual({
      exitCode: 0,
      output: expect.any(String),
    });
  });

  test("breaks a member's type as Biome does, and leaves one name and NULL as it is", async () => {
    const date = keyword("Date");
    const string = keyword("string");
    const nulls = {
      kind: "union",
      members: [string, keyword("null")],
    } as const;
    const alias: TsType = { kind: "alias", name: "BillingInvoicesState" };
    const key =
      "the_state_of_the_invoice_that_was_placed_long_ago_and_very_long";
    const source = file(
      query("long", "select 1", {
        fields: [
          { name: `${key}_a`, values: same(keyword("bigint")), nullable: true },
          {
            name: `${key}_b`,
            values: same({ kind: "union", members: [date, string] }),
            nullable: false,
          },
          {
            name: `${key}_c`,
            values: same({ kind: "array", element: nulls, readonly: true }),
            nullable: false,
          },
          {
            name: `${key}_d`,
            values: same({ kind: "array", element: nulls, readonly: false }),
            nullable: true,
          },
          { name: `${key}_and_more`, values: same(alias), nullable: true },
          { name: `${key}_and_also`, values: same(date), nullable: true },
          {
            name: `${key}_and_then`,
            values: same({ kind: "array", element: alias, readonly: true }),
            nullable: false,
          },
          {
            name: `${key}_at`,
            values: same({
              kind: "array",
              element: {
                kind: "union",
                members: [
                  { kind: "union", members: [date, string] },
                  keyword("null"),
                ],
              },
              readonly: true,
            }),
            nullable: false,
          },
        ],
      }),
    );

    expect(body(source)).toStartWith(`/** A row of {@link long}. */
export interface LongRow {
  ${key}_a:
    | bigint
    | null;
  ${key}_b:
    | Date
    | string;
  ${key}_c: readonly (
    | string
    | null
  )[];
  ${key}_d:
    | (string | null)[]
    | null;
  ${key}_and_more: Database.BillingInvoicesState | null;
  ${key}_and_also: Date | null;
  ${key}_and_then: readonly Database.BillingInvoicesState[];
  ${key}_at: readonly (
    | Date
    | string
    | null
  )[];
}`);
    expect(await check(source)).toEqual({
      exitCode: 0,
      output: expect.any(String),
    });
  });
});
